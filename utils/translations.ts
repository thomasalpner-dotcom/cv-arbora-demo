// Simple event emitter system to sync language across components
type LanguageChangeListener = (lang: Language) => void;
const listeners = new Set<LanguageChangeListener>();

let currentLang: Language = (localStorage.getItem('cv_arbora_lang') as Language) || 'sv';

export const getLanguage = (): Language => currentLang;

export const setLanguage = (lang: Language) => {
  if (translations[lang]) {
    currentLang = lang;
    localStorage.setItem('cv_arbora_lang', lang);
    listeners.forEach(listener => listener(lang));
  }
};

export const translate = (key: string, defaultValue?: string): string => {
  const dictionary = translations[currentLang] || translations.sv;
  return dictionary[key] || defaultValue || key;
};

// Alias t for cleaner code
export const t = translate;

export const useTranslation = () => {
  const [lang, setLangState] = useState<Language>(currentLang);

  useEffect(() => {
    const handleLanguageChange = (newLang: Language) => {
      setLangState(newLang);
    };
    listeners.add(handleLanguageChange);
    return () => {
      listeners.delete(handleLanguageChange);
    };
  }, []);

  return {
    t: (key: string, defaultValue?: string) => translations[lang]?.[key] || defaultValue || key,
    currentLanguage: lang,
    setLanguage
  };
};
